type NestedKeyOf<O extends object> = {
	[K in keyof O & (string | number)]: O[K] extends object
		? `${K}` | `${K}.${NestedKeyOf<O[K]>}`
		: `${K}`
}[keyof O & (string | number)]

export type TranslationKey = NestedKeyOf<TranslationSchema>
